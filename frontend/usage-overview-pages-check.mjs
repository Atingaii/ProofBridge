import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = readFileSync(new URL('./src/app/lib/usageOverviewPages.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { mergeUsageOverviewPage: merge } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const metrics = (n, known = true) => ({ inputTokens: n, outputTokens: n, cacheTokens: n, totalTokens: n * 3, estimatedCostUsd: n / 100, callCount: n, costKnown: known });
const page = (id, n = 1, known = true, machineId = 'shared') => ({ overview: { ...metrics(n, known), days: 30, timezoneOffset: 0, items: [{ ...metrics(n, known), runId: id, machineId }], trend: [{ ...metrics(n, known), date: '2026-10-03' }] }, page: { scannedRuns: 1, hasMore: true } });
const empty = { overview: { ...metrics(0, false), days: 30, timezoneOffset: 0, items: [], trend: [] }, page: { scannedRuns: 1, hasMore: true } };
let state = merge(null, empty, '');
assert.equal(state.overview.costKnown, false);
state = merge(state, page('a'), 'second');
const snapshot = JSON.stringify(state.overview);
const first = state;
assert.equal(state.scannedRuns, 2); assert.equal(state.overview.costKnown, true);
assert.equal(merge(state, page('a'), 'second'), state, 'same cursor is entirely idempotent');
state = merge(state, page('a'), 'duplicate-run');
assert.equal(state.scannedRuns, 2); assert.equal(state.overview.totalTokens, 3, 'same run on another cursor is not added twice');
state = merge(state, empty, 'empty-middle');
assert.equal(state.overview.costKnown, true, 'empty source page cannot poison known costs');
state = merge(state, page('b', 2), 'third');
assert.equal(state.overview.machines, 1); assert.equal(state.overview.runs, 2);
assert.equal(state.overview.totalTokens, 9); assert.equal(state.overview.trend[0].totalTokens, 9);
assert.equal(state.overview.trend[0].costKnown, true);
state = merge(state, page('c', 3, false, 'other'), 'fourth');
assert.equal(state.overview.costKnown, false); assert.equal(state.overview.trend[0].costKnown, false);
assert.equal(state.overview.machines, 2); assert.equal(state.overview.runs, 3);
assert.equal(state.overview.callCount, 6); assert.equal(state.overview.estimatedCostUsd, .06);
assert.equal(state.scannedRuns, 5); assert.equal(JSON.stringify(first.overview), snapshot, 'merge must not mutate prior visible data');
const earlier = page('d'); earlier.overview.trend[0].date = '2026-10-01';
state = merge(state, earlier, 'fifth'); assert.deepEqual(state.overview.trend.map(point => point.date), ['2026-10-01', '2026-10-03']);
const invalid = page('e'); invalid.overview.items.push(page('f').overview.items[0]);
assert.throws(() => merge(state, invalid, 'invalid'), /single-run/, 'cannot guess overlapping multi-run aggregate trends');
console.log('Usage page merge passed: cursor/run idempotence, source progress, empty costs, unique machines, date sums/AND, ordering and immutability.');
